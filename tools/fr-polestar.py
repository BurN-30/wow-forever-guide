"""The French that Polestar's own Alliance guides lack, listed for translation and shipped with the module.

  python tools/fr-polestar.py <Polestar checkout of the shipped version>

Reads the checkout's guides/locales/frFR files (the source of Polestar_frFR/Texts.lua: forge guide
compile writes one from the other, same keys) for the guides of Polestar's Alliance route: every file
under forever/alliance/, plus Shen'dralas and Mount Hyjal (forever/40-50/shendralas,
forever/50-60/mount-hyjal), which the route chains into. A text is "missing" when Polestar leaves it
"" (the English shows).

1. tools/fr-texts-polestar-manquants.json: every missing English text, sorted, as a dictionary
   English -> French like tools/fr-texts.json; the French already written there is kept, a text
   Polestar has translated since is dropped. Translate the "" values (impersonal French, every
   {kind:id} token kept as it is: the game writes its French name there).
2. addons-src/Polestar_frFR/Complement.lua: for each guide, its missing texts that the JSON
   translates (tokens checked), and the Polestar version they were read from, as a block of Lua that
   tools/build.py puts into Polestar_frFR/Texts.lua right before its RegisterGuideTexts call: the
   block fills only the texts Polestar's table leaves without French (nil or ""), never one that
   Polestar translated. Texts.lua runs while Polestar itself loads (Core/Locale.lua loads the
   language folder), before any other addon, so the French has to be in that file. tools/build.py
   warns when the release it copies is another version: run this again on that version's checkout.

Prints, per guide, the texts, the missing ones and how many of those the JSON translates.
"""
import json, pathlib, re, sys

REPO = pathlib.Path(__file__).resolve().parent.parent
JSON = REPO / "tools" / "fr-texts-polestar-manquants.json"
LUA = REPO / "addons-src" / "Polestar_frFR" / "Complement.lua"
KEY = re.compile(r'^\t\["(.*)"\] = "(.*)",$')
HEAD = re.compile(r"^-- French \(frFR\): the guide (\S+) ")
TOKEN = re.compile(r"\{[a-z]+:\d+\}")
NOTICE = "Modified by BurN-30 on 2026-11-23 (github.com/BurN-30/wow-forever-guide)"
ROUTE = ["forever/alliance/", "forever/40-50/shendralas.lua", "forever/50-60/mount-hyjal.lua"]


def unlua(s):
    return re.sub(r'\\(.)', lambda m: {"n": "\n", '"': '"', "\\": "\\"}.get(m.group(1), m.group(0)), s)


def lua(s):
    return s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")


def read(root):
    base = root / "guides" / "locales" / "frFR"
    guides = {}
    for p in sorted(base.rglob("*.lua")):
        rel = p.relative_to(base).as_posix()
        if not any(rel == r or (r.endswith("/") and rel.startswith(r)) for r in ROUTE):
            continue
        gid, texts = None, {}
        for line in p.read_text(encoding="utf-8").split("\n"):
            m = HEAD.match(line)
            if m and not gid:
                gid = m.group(1)
            m = KEY.match(line)
            if m:
                texts[unlua(m.group(1))] = unlua(m.group(2))
        if gid:
            guides[gid] = texts
    return guides


def version(root):
    pj = root / "guides" / "pack.json"
    return json.loads(pj.read_text(encoding="utf-8")).get("version", "?")


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    root = pathlib.Path(sys.argv[1])
    sys.stdout.reconfigure(encoding="utf-8")
    guides = read(root)
    if not guides:
        sys.exit(f"no Alliance guide texts under {root}/guides/locales/frFR")
    ver = version(root)
    old = json.loads(JSON.read_text(encoding="utf-8")) if JSON.exists() else {}
    missing = sorted({en for texts in guides.values() for en, fr in texts.items() if fr == ""})
    out = {en: old.get(en, "") for en in missing}
    JSON.write_text(json.dumps(out, ensure_ascii=False, indent=2) + "\n", encoding="utf-8", newline="\n")
    bad = [en for en, fr in out.items() if fr and sorted(TOKEN.findall(en)) != sorted(TOKEN.findall(fr))]
    for en in bad:
        print("TOKENS DIFFER, left out:", en)
    lines = [
        "-- " + NOTICE + ": French for the texts of",
        "-- Polestar's Alliance route that Polestar leaves in English (translations by BurN-30, GPL-3.0),",
        "-- only where this table has none: a text Polestar translated keeps Polestar's words.",
        "-- Generated by tools/fr-polestar.py from Polestar " + ver + "'s guides/locales/frFR and",
        "-- tools/fr-texts-polestar-manquants.json; put here by tools/build.py.",
        "-- Polestar version: " + ver,
        "do",
        "\tlocal add = {}",
    ]
    total = trans = given = 0
    print(f"Polestar {ver}: {len(guides)} guides")
    for gid in sorted(guides):
        texts = guides[gid]
        gone = [en for en, fr in texts.items() if fr == ""]
        ours = [en for en in gone if out.get(en) and en not in bad]
        total += len(texts)
        trans += len(texts) - len(gone)
        given += len(ours)
        print(f"  {gid:50} {len(texts):5} texts {len(gone):4} without French {len(ours):4} from us")
        if ours:
            lines.append(f'\tadd["{gid}"] = {{')
            for en in sorted(ours):
                lines.append(f'\t\t["{lua(en)}"] = "{lua(out[en])}",')
            lines.append("\t}")
    lines += [
        '\tt.guides = type(t.guides) == "table" and t.guides or {}',
        "\tfor id, list in pairs(add) do",
        "\t\tlocal g = t.guides[id]",
        '\t\tif type(g) ~= "table" then',
        "\t\t\tg = {}",
        "\t\t\tt.guides[id] = g",
        "\t\tend",
        "\t\tfor en, fr in pairs(list) do",
        '\t\t\tif g[en] == nil or g[en] == "" then g[en] = fr end',
        "\t\tend",
        "\tend",
        "end",
        "",
    ]
    LUA.parent.mkdir(parents=True, exist_ok=True)
    LUA.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"TOTAL {total} texts, {trans} with Polestar's French, {total - trans} without; "
          f"{len(missing)} distinct texts to translate, {sum(1 for v in out.values() if v)} translated in "
          f"{JSON.name}; {given} texts completed in {LUA.name}")


if __name__ == "__main__":
    main()
