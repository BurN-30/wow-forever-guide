"""This pack's in-game release notes: CHANGELOG.md's "### En jeu" and "### In game" of a version, as Lua.

  python tools/notes-jeu.py <version> <out Notes.lua> [<CHANGELOG.md>]

tools/build.py writes Polestar/GroupeAlliance/Notes.lua with it, for the version of pack/pack.json.
In the section "## v<version>" of CHANGELOG.md, the bullets of "### En jeu" (French client) and
"### In game" (any other) become the notes of Polestar's "What's new" window, under this pack's own
title (Greffe.lua, GA.NOTES): once per account and per version. Each bullet is
"- **Heading** : text" (French) or "- **Heading**: text"; without a bold heading, the words before
the first colon are the heading when short, else "Groupe Alliance". A version without these two
sub-sections has no in-game notes (GA.NOTES = nil): the window does not open for it. The installer's
notes (### Français, ### English) are not read here.
"""
import pathlib, re, sys

REPO = pathlib.Path(__file__).resolve().parent.parent


def section(text, version):
    m = re.search(rf"^## v{re.escape(version)}\b.*?$(.*?)(?=^## v|\Z)", text, re.M | re.S)
    return m.group(1) if m else ""


def bullets(sec, title):
    m = re.search(rf"^### {re.escape(title)}\s*$(.*?)(?=^### |\Z)", sec, re.M | re.S)
    if not m:
        return []
    out = []
    for line in m.group(1).splitlines():
        if line.startswith("- "):
            out.append(line[2:].strip())
        elif line.startswith("  ") and out:
            out[-1] += " " + line.strip()
    return out


def plain(s):
    s = re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", s)
    return s.replace("`", "").replace("**", "").strip()


def note(b, fallback):
    m = re.match(r"\*\*(.+?)\*\*\s*:?\s*(.*)$", b)
    if m:
        return plain(m.group(1)), plain(m.group(2))
    head, sep, rest = b.partition(":")
    if sep and len(head) <= 50:
        return plain(head), plain(rest)
    return fallback, plain(b)


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def notes_lua(version, changelog_text):
    sec = section(changelog_text, version)
    fr = [note(b, "Groupe Alliance") for b in bullets(sec, "En jeu")]
    en = [note(b, "Group Alliance") for b in bullets(sec, "In game")]
    head = ["-- Generated by tools/notes-jeu.py from CHANGELOG.md (## v" + version + ", ### En jeu and ### In game).",
            "-- Do not edit: tools/build.py writes it again. Read by Greffe.lua (GA.NOTES).",
            "local _, ns = ...", "local GA = ns.GA or {}", "ns.GA = GA", ""]
    if not (fr or en):
        return "\n".join(head + ["GA.NOTES = nil -- no in-game notes for " + version, ""])
    fr, en = fr or en, en or fr
    lines = head + ["GA.NOTES = {", f"\tversion = {lua_str(version)},"]
    for key, list_ in (("frFR", fr), ("enUS", en)):
        lines.append(f"\t{key} = {{")
        for h, t in list_:
            lines.append(f"\t\t{{ {lua_str(h)}, {lua_str(t)} }},")
        lines.append("\t},")
    lines += ["}", ""]
    return "\n".join(lines)


def main():
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    version, out = sys.argv[1], pathlib.Path(sys.argv[2])
    src = pathlib.Path(sys.argv[3]) if len(sys.argv) > 3 else REPO / "CHANGELOG.md"
    out.write_text(notes_lua(version, src.read_text(encoding="utf-8-sig")), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
